// Synthetic reports exercise rejection controls only; actual RED evidence is generated by Playwright.
function report() {
  return {
    config: { maxFailures: 0, projects: [{ retries: 0 }], workers: 1 },
    errors: [],
    stats: { expected: 0, flaky: 0, skipped: 0, unexpected: 1 },
    suites: [
      {
        specs: [
          {
            file: 'canary.spec.mjs',
            tests: [
              {
                expectedStatus: 'passed',
                projectName: 'nightly-fix-proof',
                results: [
                  {
                    errors: [
                      {
                        location: { file: '/scratch/canary.spec.mjs' },
                        message: 'expect(received).toBe(expected)\nExpected: 6\nReceived: 5',
                      },
                    ],
                    status: 'failed',
                  },
                ],
                status: 'unexpected',
              },
            ],
            title: TITLE,
          },
        ],
      },
    ],
  };
}

test('report admission requires the single real intended failure with zero retries', () => {
  validateReport(report(), 'failure', 'failure');
  for (const [outcome, status] of [
    ['success', 'failure'],
    ['failure', 'success'],
    ['skipped', 'failure'],
  ]) {
    assert.throws(() => validateReport(report(), outcome, status));
  }
  const mutations = [
    (r) => r.errors.push({ message: 'setup failed' }),
    (r) => {
      r.config.workers = 2;
    },
    (r) => {
      r.config.maxFailures = 1;
    },
    (r) => {
      r.config.projects[0].retries = 1;
    },
    (r) => {
      r.stats.expected = 1;
    },
    (r) => {
      r.stats.flaky = 1;
    },
    (r) => {
      r.suites[0].specs[0].title = 'unrelated failure';
    },
    (r) => r.suites[0].specs.push(r.suites[0].specs[0]),
    (r) => {
      r.suites[0].specs[0].tests[0].results[0].status = 'timedOut';
    },
    (r) => {
      r.suites[0].specs[0].tests[0].results[0].errors[0].message = 'setup failed';
    },
    (r) => r.suites[0].specs[0].tests[0].results.push(r.suites[0].specs[0].tests[0].results[0]),
  ];
  for (const mutate of mutations) {
    const value = report();
    mutate(value);
    assert.throws(() => validateReport(value, 'failure', 'failure'));
  }
});

