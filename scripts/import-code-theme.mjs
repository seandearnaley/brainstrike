#!/usr/bin/env node
/**
 * Prints the CodeMirror `--syntax-*` tokens for one code theme, read from the
 * Shiki themes chat code blocks use, so the editor and chat code blocks share
 * one colour source. Paste the output into packages/ui/src/themes/code-themes.css;
 * values there are never edited by hand.
 *
 *   node scripts/import-code-theme.mjs <id> <light shiki theme> <dark shiki theme>
 */
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

/** Each token, with the TextMate scopes it stands for, most representative first. */
const TOKENS = [
  ['keyword', ['keyword.control', 'keyword', 'storage.type']],
  ['string', ['string.quoted.double', 'string']],
  ['number', ['constant.numeric', 'constant']],
  ['function', ['entity.name.function', 'support.function']],
  ['type', ['support.type', 'entity.name.type', 'storage.type']],
  ['class', ['entity.name.class', 'entity.name.type.class', 'entity.name.type']],
  ['property', ['support.type.property-name', 'variable.other.property', 'meta.property-name']],
  ['tag', ['entity.name.tag']],
  ['attribute', ['entity.other.attribute-name']],
  ['comment', ['comment.line', 'comment']],
  ['invalid', ['invalid.illegal', 'invalid']],
];

const require = createRequire(new URL('../packages/ui/package.json', import.meta.url));

async function loadTheme(name) {
  const file = require.resolve(`@shikijs/themes/${name}`);
  const module = await import(pathToFileURL(file).href);
  return module.default;
}

/** Plain scope selectors only; descendant (`a b`) and exclusion selectors are skipped. */
function selectors(rule) {
  const scope = rule.scope;
  if (!scope) {
    return [];
  }
  const list = Array.isArray(scope) ? scope : scope.split(',');
  return list.map((selector) => selector.trim()).filter((selector) => !/\s/u.test(selector));
}

/** TextMate matching: a selector matches the scope itself or any child scope; longest wins, then latest. */
function resolve(theme, scope) {
  let best = null;
  for (const rule of theme.tokenColors ?? theme.settings ?? []) {
    // A rule that also paints a background (One's red `invalid` block) picks a
    // foreground for that background, not for the editor surface.
    if (!rule.settings?.foreground || rule.settings.background) {
      continue;
    }
    for (const selector of selectors(rule)) {
      if (
        (scope === selector || scope.startsWith(`${selector}.`)) &&
        (!best || selector.length >= best.selector.length)
      ) {
        best = { color: rule.settings.foreground, selector };
      }
    }
  }
  return best?.color ?? null;
}

function tokens(theme) {
  const foreground = theme.colors?.['editor.foreground'] ?? theme.fg;
  const background = theme.colors?.['editor.background'] ?? theme.bg;
  // The theme's own surface, for previews that show the scheme on its background.
  const surface = [
    `  --syntax-background: ${background.toLowerCase()};`,
    `  --syntax-foreground: ${foreground.toLowerCase()};`,
  ];
  return [
    ...surface,
    ...TOKENS.map(([name, scopes]) => {
      const resolved = scopes.map((scope) => resolve(theme, scope)).find(Boolean);
      // Invalid code reads as the editor's own error colour when the theme has one.
      const error = name === 'invalid' ? theme.colors?.['editorError.foreground'] : undefined;
      const color = error ?? resolved ?? foreground;
      return `  --syntax-${name}: ${color.toLowerCase()};`;
    }),
  ];
}

const [id, lightName, darkName] = process.argv.slice(2);
if (!(id && lightName && darkName)) {
  console.error('usage: import-code-theme.mjs <id> <light shiki theme> <dark shiki theme>');
  process.exit(1);
}
const [light, dark] = await Promise.all([loadTheme(lightName), loadTheme(darkName)]);
console.log(`/* ${id}: ${light.displayName ?? lightName} / ${dark.displayName ?? darkName}. Generated by scripts/import-code-theme.mjs. */
[data-code-theme-light="${id}"] {
${tokens(light).join('\n')}
}

.dark[data-code-theme-dark="${id}"],
.dark [data-code-theme-dark="${id}"] {
${tokens(dark).join('\n')}
}`);
