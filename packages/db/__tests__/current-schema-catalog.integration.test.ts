import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { describe, expect, it } from 'vitest';
import { migrate } from '../src/migrations/bootstrap.js';
import {
  CURRENT_SCHEMA_DDL,
  CURRENT_SCHEMA_LEDGER_KEY,
} from '../src/migrations/current-schema-ddl.js';
import { QUALIFIED_PG_TEXTSEARCH_VERSION } from '../src/pg-textsearch-compatibility.js';
import { dumpRowCounts, dumpSchema, dumpSeedData } from '../src/schema-snapshot/introspect.js';
import { TEST_ENGINE_EXTENSIONS } from './helpers/migrated-test-db.js';

/**
 * Proves the single current-schema DDL still constructs the database the
 * 151-migration chain constructed.
 *
 * The fixture is the chain's own output: generated by
 * `scripts/generate-schema-catalog-snapshot.ts` while production still replayed
 * the chain, and unchanged by the collapse. So this is a real equivalence
 * assertion and not a self-comparison -- which is exactly what it would have
 * become had the pre-collapse test been kept, since that test compared
 * `migrate()` against the DDL and `migrate()` IS the DDL now.
 *
 * Compared on catalog readback, never on the SQL that produced it, so a default
 * Postgres rewrote or an index parameter that silently fell back to its own
 * default shows up as a diff.
 *
 * Deliberately NOT snapshot-restored (`createMigratedTestDb`): the subject is
 * schema construction itself, so it must run from initdb for real.
 *
 * A deliberate schema change regenerates the fixture
 * (`pnpm --filter @brainstrike/db db:schema:catalog`) in the same commit, and the
 * diff is the review surface for what moved.
 */

/**
 * Revoked by migration 074 and deliberately preserved by migration 151. Named
 * here rather than derived, on purpose: this is the SECOND instrument. The
 * generator derives the revoke list from a catalog diff against a pristine
 * database, so if that derivation ever silently produced an empty list, a
 * derived expectation would agree with it and prove nothing.
 */
const SANDBOX_ESCAPE_FUNCTIONS = [
  'pg_sleep(double precision)',
  'pg_sleep_for(interval)',
  'pg_sleep_until(timestamp with time zone)',
  'set_config(text, text, boolean)',
] as const;

const SNAPSHOT_FIXTURE = fileURLToPath(
  new URL('./fixtures/schema-catalog.snapshot.txt', import.meta.url)
);

async function bootProductionAndDump(): Promise<string> {
  const db = new PGlite({ extensions: TEST_ENGINE_EXTENSIONS });
  try {
    await migrate(db);
    return [await dumpSchema(db), await dumpRowCounts(db), await dumpSeedData(db)].join('\n');
  } finally {
    await db.close();
  }
}

describe('current-schema catalog', () => {
  it('boots the schema, row counts and seed rows the migration chain built', async () => {
    const [dump, expected] = await Promise.all([
      bootProductionAndDump(),
      readFile(SNAPSHOT_FIXTURE, 'utf-8'),
    ]);

    expect(dump).toBe(expected);
  }, 120_000);

  it('covers the schema surface a collapse could silently drop', async () => {
    const dump = await bootProductionAndDump();

    // Guards the guard: if the dumper stopped reporting a section, the
    // assertion above would compare two equally-empty documents and pass.
    // These are the exact surfaces the collapse was required to preserve.
    expect(dump).toContain('extension vector');
    expect(dump).toContain('extension pg_trgm');
    // The qualified pg_textsearch engine, by version. The chain's migration 066
    // carried a DO block that refused to build the BM25 index unless the
    // installed extension was exactly this version; per
    // src/pg-textsearch-compatibility.ts that guard "never re-runs for an
    // already-migrated database", so it only ever fired on a FRESH install --
    // which is precisely what this test boots. Asserting the version against
    // the frozen fixture is strictly stronger than the apply-time block: a
    // silent engine drift now fails the comparison above as well.
    expect(dump).toContain(`extension pg_textsearch version=${QUALIFIED_PG_TEXTSEARCH_VERSION}`);
    // Generated tsvector columns (chain migrations 019/034).
    expect(dump).toMatch(/column file_chunks\.\d+\.content_tsvector .*generated=s/);
    // The job-queue claim index (chain migrations 007/008).
    expect(dump).toContain('CREATE INDEX idx_job_queue_state_run_at');
    // Vector index access method (chain migration 067).
    expect(dump).toContain('am=hnsw');
    // Dimensionless embedding column (chain migrations 010/014).
    expect(dump).toMatch(/column file_chunks\.\d+\.embedding type=vector /);
    // Seeded provider/model catalog.
    expect(dump).toMatch(/rows models = \d+/);
    expect(dump).toMatch(/rows providers = \d+/);
  }, 120_000);

  it('keeps PUBLIC EXECUTE revoked on the sandbox-escape functions', async () => {
    // The chain revoked these in migration 074, and migration 151 deliberately
    // left the revokes in place when it dropped the read-only role. They are
    // not hardening theatre: `pg_sleep*` plans at cost 0.01, so the EXPLAIN cost
    // gate admits `SELECT pg_sleep(86400)` as a denial-of-service primitive, and
    // `set_config(..., is_local => false)` reaches session GUCs.
    //
    // The fixture comparison above already catches a dropped revoke, because
    // FUNCTION PRIVILEGES is one of its sections. This case is named separately
    // so a failure says WHY it matters instead of printing a one-line diff, and
    // so the property survives any future reshaping of the dump format.
    //
    // An earlier version of this collapse DID drop them: the generator emitted
    // only `public`-schema objects, these live in `pg_catalog`, and the
    // then-current equivalence test compared no ACLs at all -- so it reported a
    // zero diff while restoring public EXECUTE to every role.
    const db = new PGlite({ extensions: TEST_ENGINE_EXTENSIONS });
    try {
      await migrate(db);
      for (const signature of SANDBOX_ESCAPE_FUNCTIONS) {
        const granted = await db.query<{ can: boolean }>(
          'SELECT has_function_privilege($1, $2, $3) AS can',
          ['public', signature, 'EXECUTE']
        );
        expect(granted.rows[0]?.can, `PUBLIC must not execute ${signature}`).toBe(false);
      }
    } finally {
      await db.close();
    }
  }, 120_000);

  it('derives the ledger key from the DDL, so a schema change cannot keep it', () => {
    // The key is the schema's identity: a changed schema must present a changed
    // key, or an already-built profile would silently stay on the old schema
    // instead of being rejected by `assertNoStaleDrizzleMigrationLedger`.
    const digest = createHash('sha256').update(CURRENT_SCHEMA_DDL, 'utf-8').digest('hex');
    expect(CURRENT_SCHEMA_LEDGER_KEY).toBe(`custom-current-schema-${digest}`);
  });

  it('records exactly one applied migration', async () => {
    const db = new PGlite({ extensions: TEST_ENGINE_EXTENSIONS });
    try {
      await migrate(db);
      const applied = await db.query<{ hash: string }>(
        'SELECT hash FROM "__drizzle_migrations" ORDER BY id'
      );
      expect(applied.rows.map((row) => row.hash)).toEqual([CURRENT_SCHEMA_LEDGER_KEY]);
    } finally {
      await db.close();
    }
  }, 120_000);
});
