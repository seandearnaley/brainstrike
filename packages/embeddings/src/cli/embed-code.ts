/**
 * Configuration for the CLI tool
 */
interface EmbedCodeConfig {
  /** Chunk overlap in lines */
  chunkOverlap?: number;
  /** Custom patterns to exclude */
  exclude?: string[];
  /** Output format */
  format: 'json' | 'csv' | 'pgvector';
  /** Custom file patterns to include */
  include?: string[];
  /** Maximum file size in bytes */
  maxFileSize?: number;
  /** Maximum lines per chunk */
  maxLines?: number;
  /** Model configuration to use for embeddings */
  modelConfig: ModelConfig;
  /** Output file path */
  output?: string;
  /** Root directory to scan for code files */
  rootDir: string;
  /** Verbose logging */
  verbose?: boolean;
}

type NormalizedEmbedCodeConfig = EmbedCodeConfig &
  Required<Pick<EmbedCodeConfig, 'chunkOverlap' | 'maxFileSize' | 'maxLines' | 'verbose'>>;

/**
 * Represents an embedded code chunk
 */
interface CodeEmbedding {
  /** Content of the code chunk */
  content: string;
  /** Embedding dimensions */
  dimensions: number;
  /** Generated embedding vector */
  embedding: number[];
  /** End line number in the file */
  endLine: number;
  /** File path relative to root */
  filePath: string;
  /** Unique identifier for the chunk */
  id: string;
  /** Programming language detected */
  language: string;
  /** Model used for embedding */
  model: string;
  /** Start line number in the file */
  startLine: number;
  /** Timestamp when embedding was created */
  timestamp: string;
}

/**
 * Serialize text for PostgreSQL SQL scripts generated by this CLI.
 * Requires those scripts to set standard_conforming_strings = on before execution.
 */
function toPostgresStringLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function toCsvCell(value: string): string {
  return `"${value.replaceAll('"', '""')}"`;
}

/**
 * CLI tool for embedding code files
 */
export class CodeEmbeddingCLI {
  private readonly service: SimpleEmbeddingService;
  private readonly config: NormalizedEmbedCodeConfig;

  constructor(config: EmbedCodeConfig) {
    this.config = {
      maxFileSize: 1024 * 1024, // 1MB default
      maxLines: 100, // 100 lines per chunk
      chunkOverlap: 10, // 10 lines overlap
      verbose: false,
      ...config,
    };
    if (this.config.chunkOverlap >= this.config.maxLines) {
      throw new Error('chunkOverlap must be less than maxLines');
    }
    this.service = new SimpleEmbeddingService();
  }

  /**
   * Initialize the embedding service with the specified model
   */
  async initialize(): Promise<void> {
    const modelConfig = this.config.modelConfig;

    this.log(`Initializing embedding service with model: ${modelConfig.name}`);

    await this.service.initializeWithModel(modelConfig, (progress: EmbeddingProgress) => {
      if (this.config.verbose) {
        this.log(`${progress.stage}: ${progress.message} (${progress.progress?.toFixed(1)}%)`);
      }
    });

    this.log('Model initialized successfully!');
  }

  /**
   * Find all code files matching the patterns
   */
  async findCodeFiles(): Promise<string[]> {
    const patterns = this.config.include || DEFAULT_CODE_PATTERNS;
    const excludePatterns = [...(this.config.exclude || []), ...DEFAULT_EXCLUDE_PATTERNS];

    this.log(`Scanning for code files in: ${this.config.rootDir}`);
    this.log(`Include patterns: ${patterns.join(', ')}`);
    this.log(`Exclude patterns: ${excludePatterns.join(', ')}`);

    const allFiles: string[] = [];

    for (const pattern of patterns) {
      const files = await glob(pattern, {
        cwd: this.config.rootDir,
        ignore: excludePatterns,
        absolute: false,
      });
      allFiles.push(...files);
    }

    // Remove duplicates and filter by file size
    const uniqueFiles = [...new Set(allFiles)];
    const validFiles: string[] = [];

    for (const file of uniqueFiles) {
      const fullPath = path.join(this.config.rootDir, file);
      try {
        const stats = fs.statSync(fullPath);
        if (stats.size <= (this.config.maxFileSize || 1024 * 1024)) {
          validFiles.push(file);
        } else {
          this.log(`Skipping ${file}: file too large (${stats.size} bytes)`);
        }
      } catch {
        this.log(`Skipping ${file}: cannot read file stats`);
      }
    }

    this.log(`Found ${validFiles.length} code files to process`);
    return validFiles;
  }

  /**
   * Split file content into chunks
   */
  splitIntoChunks(
    content: string,
    _filePath: string
  ): Array<{
    content: string;
    startLine: number;
    endLine: number;
  }> {
    const lines = content.split('\n');
    const chunks: Array<{ content: string; startLine: number; endLine: number }> = [];
    const maxLines = this.config.maxLines ?? 100;
    const overlap = this.config.chunkOverlap ?? 10;

    let startLine = 0;

    while (startLine < lines.length) {
      const endLine = Math.min(startLine + maxLines, lines.length);
      const chunkLines = lines.slice(startLine, endLine);

      if (chunkLines.length > 0) {
        chunks.push({
          content: chunkLines.join('\n'),
          startLine: startLine + 1, // 1-based line numbers
          endLine,
        });
      }

      if (endLine >= lines.length) {
        break;
      }

      // Move start position with overlap while guaranteeing forward progress.
      const nextStartLine = Math.max(0, endLine - overlap);
      if (nextStartLine <= startLine) {
        break;
      }
      startLine = nextStartLine;
    }

    return chunks;
  }

  /**
   * Detect programming language from file extension
   */
  detectLanguage(filePath: string): string {
    const ext = path.extname(filePath).toLowerCase();
    const languageMap: Record<string, string> = {
      '.js': 'javascript',
      '.jsx': 'javascript',
      '.ts': 'typescript',
      '.tsx': 'typescript',
      '.py': 'python',
      '.java': 'java',
      '.c': 'c',
      '.cpp': 'cpp',
      '.h': 'c',
      '.hpp': 'cpp',
      '.cs': 'csharp',
      '.go': 'go',
      '.rs': 'rust',
      '.rb': 'ruby',
      '.php': 'php',
      '.swift': 'swift',
      '.kt': 'kotlin',
      '.scala': 'scala',
      '.r': 'r',
      '.sql': 'sql',
      '.sh': 'shell',
      '.bash': 'shell',
      '.zsh': 'shell',
      '.fish': 'shell',
      '.ps1': 'powershell',
      '.dockerfile': 'dockerfile',
      '.yml': 'yaml',
      '.yaml': 'yaml',
      '.json': 'json',
      '.toml': 'toml',
      '.xml': 'xml',
      '.html': 'html',
      '.css': 'css',
      '.scss': 'scss',
      '.sass': 'sass',
      '.vue': 'vue',
      '.svelte': 'svelte',
    };

    return languageMap[ext] || 'text';
  }

  /**
   * Process all code files and generate embeddings
   */
  async processFiles(): Promise<CodeEmbedding[]> {
    const files = await this.findCodeFiles();
    const allEmbeddings: CodeEmbedding[] = [];
    let processedFiles = 0;

    for (const file of files) {
      try {
        const fileEmbeddings = await this.processSingleFile(file);
        allEmbeddings.push(...fileEmbeddings);
        processedFiles++;
        this.log(`Progress: ${processedFiles}/${files.length} files processed`);
      } catch (error) {
        this.log(`Error processing ${file}: ${error}`);
      }
    }

    return allEmbeddings;
  }

  private async processSingleFile(file: string): Promise<CodeEmbedding[]> {
    const fullPath = path.join(this.config.rootDir, file);
    const content = fs.readFileSync(fullPath, 'utf-8');
    const language = this.detectLanguage(file);
    const chunks = this.splitIntoChunks(content, file);

    this.log(`Processing ${file} (${chunks.length} chunks)`);

    const embeddings: CodeEmbedding[] = [];
    for (let i = 0; i < chunks.length; i++) {
      const chunk = chunks[i];
      if (!chunk) {
        continue;
      }
      const embedding = await this.embedChunk(file, language, chunk, i, chunks.length);
      if (embedding) {
        embeddings.push(embedding);
      }
    }
    return embeddings;
  }

  private async embedChunk(
    file: string,
    language: string,
    chunk: { content: string; startLine: number; endLine: number },
    index: number,
    total: number
  ): Promise<CodeEmbedding | null> {
    const id = `${file}:${chunk.startLine}-${chunk.endLine}`;
    try {
      const result: EmbeddingResult = await this.service.generateDocEmbedding(chunk.content);
      if (this.config.verbose) {
        this.log(`  Chunk ${index + 1}/${total}: ${id}`);
      }
      return {
        id,
        filePath: file,
        language,
        content: chunk.content,
        startLine: chunk.startLine,
        endLine: chunk.endLine,
        embedding: result.embedding,
        dimensions: result.dimensions,
        model: result.model,
        timestamp: new Date().toISOString(),
      };
    } catch (error) {
      this.log(`Error embedding chunk ${id}: ${error}`);
      return null;
    }
  }

  /**
   * Save embeddings to file
   */
  async saveEmbeddings(embeddings: CodeEmbedding[]): Promise<void> {
    if (!this.config.output) {
      return;
    }

    const outputPath = this.config.output;
    this.log(`Saving ${embeddings.length} embeddings to: ${outputPath}`);

    switch (this.config.format) {
      case 'json':
        fs.writeFileSync(outputPath, JSON.stringify(embeddings, null, 2));
        break;

      case 'csv': {
        const csvHeader =
          'id,file_path,language,start_line,end_line,dimensions,model,timestamp,content,embedding\n';
        const csvRows = embeddings.map(
          (e) =>
            `${toCsvCell(e.id)},${toCsvCell(e.filePath)},${toCsvCell(e.language)},${e.startLine},${e.endLine},${e.dimensions},${toCsvCell(e.model)},${toCsvCell(e.timestamp)},${toCsvCell(e.content)},${toCsvCell(`[${e.embedding.join(',')}]`)}`
        );
        fs.writeFileSync(outputPath, csvHeader + csvRows.join('\n'));
        break;
      }

      case 'pgvector': {
        // Generate SQL for PostgreSQL with pgvector extension
        const sqlStatements = embeddings.map((e) => {
          const vectorString = `[${e.embedding.join(',')}]`;
          return [
            'INSERT INTO code_embeddings',
            '(id, file_path, language, start_line, end_line, content, embedding, model, created_at)',
            `VALUES (${toPostgresStringLiteral(e.id)}, ${toPostgresStringLiteral(e.filePath)}, ${toPostgresStringLiteral(e.language)},`,
            `${e.startLine}, ${e.endLine}, ${toPostgresStringLiteral(e.content)},`,
            `${toPostgresStringLiteral(vectorString)}::vector, ${toPostgresStringLiteral(e.model)},`,
            `${toPostgresStringLiteral(e.timestamp)});`,
          ].join(' ');
        });

        const sqlContent = `-- Code embeddings generated at ${new Date().toISOString()}\n-- Total embeddings: ${embeddings.length}\n\nSET standard_conforming_strings = on;\n\n${sqlStatements.join('\n\n')}`;
        fs.writeFileSync(outputPath, sqlContent);
        break;
      }

      default:
        throw new Error(`Unsupported output format: ${this.config.format}`);
    }

    this.log(`Successfully saved embeddings to ${outputPath}`);
  }

  /**
   * Run the complete embedding process
   */
  async run(): Promise<void> {
    try {
      await this.initialize();
      const embeddings = await this.processFiles();
      await this.saveEmbeddings(embeddings);

      this.log('\nCompleted successfully!');
      this.log(`Total embeddings generated: ${embeddings.length}`);

      const modelConfig = this.service.getCurrentModelConfig();
      if (modelConfig) {
        this.log(`Model used: ${modelConfig.name} (${modelConfig.dimensions}D)`);
      }
    } catch {
      process.exit(1);
    } finally {
      await this.service.dispose();
    }
  }

  /**
   * Utility logging method - writes to stderr for CLI output (not debugging)
   */
  private log(message: string): void {
    if (this.config.verbose || !this.config.output) {
      // biome-ignore lint/suspicious/noConsole: CLI tool intentionally uses stderr for output
      console.error(message);
    }
  }
}

/**
 * Validate and require a command line argument value
 */
function requireArgValue(_argName: string, value: string | undefined): string {
  if (!value) {
    process.exit(1);
  }
  return value;
}

/**
 * Parse a single command line option
 */
function parseOption(
  config: Partial<EmbedCodeConfig>,
  arg: string,
  nextArg: string | undefined
): boolean {
  switch (arg) {
    case '--include':
      config.include = requireArgValue(arg, nextArg).split(',');
      return true;
    case '--exclude':
      config.exclude = requireArgValue(arg, nextArg).split(',');
      return true;
    case '--format': {
      const format = requireArgValue(arg, nextArg);
      if (!['json', 'csv', 'pgvector'].includes(format)) {
        process.exit(1);
      }
      config.format = format as 'json' | 'csv' | 'pgvector';
      return true;
    }
    case '--output':
      config.output = requireArgValue(arg, nextArg);
      return true;
    case '--max-file-size':
      config.maxFileSize = Number.parseInt(requireArgValue(arg, nextArg), 10);
      return true;
    case '--max-lines':
      config.maxLines = Number.parseInt(requireArgValue(arg, nextArg), 10);
      return true;
    case '--chunk-overlap':
      config.chunkOverlap = Number.parseInt(requireArgValue(arg, nextArg), 10);
      return true;
    case '--verbose':
      config.verbose = true;
      return false; // no value consumed
    default:
      process.exit(1);
  }
}

/**
 * Parse command line arguments
 */
function parseArguments(args: string[]): EmbedCodeConfig | null {
  if (args.length === 0 || args.includes('--help') || args.includes('-h')) {
    return null;
  }

  const rootDir = args[0];
  if (!rootDir) {
    process.exit(1);
  }

  if (!fs.existsSync(rootDir)) {
    process.exit(1);
  }

  const config: Partial<EmbedCodeConfig> = {
    rootDir,
    format: 'json',
  };

  // Parse command line arguments
  for (let i = 1; i < args.length; i++) {
    const arg = args[i];
    if (!arg) {
      continue;
    }

    const nextArg = args[i + 1];

    if (parseOption(config, arg, nextArg)) {
      i++; // Skip next arg if it was consumed
    }
  }

  // CLI always uses FALLBACK_MODEL_CONFIG since it runs standalone without database access
  // rootDir is guaranteed to exist from validation above
  return {
    ...config,
    rootDir,
    format: config.format || 'json',
    modelConfig: FALLBACK_MODEL_CONFIG,
  };
}

/**
 * CLI entry point
 */
async function main() {
  const args = process.argv.slice(2);
  const config = parseArguments(args);

  if (!config) {
    process.exit(0);
  }

  const cli = new CodeEmbeddingCLI(config);
  await cli.run();
}

// Run CLI if this file is executed directly (CJS) — ESM-safe guard
const canRunDirect =
  typeof require !== 'undefined' && typeof module !== 'undefined' && require.main === module;
if (canRunDirect) {
  main().catch((error) => {
    // CLI error handling - output to stderr and exit
    process.stderr.write(`Error: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  });
}
