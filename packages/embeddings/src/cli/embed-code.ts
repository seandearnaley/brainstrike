  '**/*.jsx',
  '**/*.ts',
  '**/*.tsx',
  '**/*.py',
  '**/*.java',
  '**/*.c',
  '**/*.cpp',
  '**/*.h',
  '**/*.hpp',
  '**/*.cs',
  '**/*.go',
  '**/*.rs',
  '**/*.rb',
  '**/*.php',
  '**/*.swift',
  '**/*.kt',
  '**/*.scala',
  '**/*.r',
  '**/*.sql',
