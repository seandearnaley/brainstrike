// Regenerates src/registry.generated.ts from src/commands/*.ts.
//   node scripts/build-registry.mjs          write the registry
//   node scripts/build-registry.mjs --check  exit 1 when the registry is stale
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const commandsDir = join(root, 'src', 'commands');
const registry = join(root, 'src', 'registry.generated.ts');

const names = readdirSync(commandsDir)
  .filter((file) => file.endsWith('.ts'))
  .map((file) => file.slice(0, -'.ts'.length))
  .sort();
const sources = createHash('sha256');
for (const name of names) {
  sources.update(`${name}\n${readFileSync(join(commandsDir, `${name}.ts`), 'utf8')}\n`);
}
const content = [
  '// Generated by `node scripts/build-registry.mjs`. Do not edit by hand.',
  `// sources: ${sources.digest('hex')}`,
  ...names.map((name) => `import { run as ${name} } from './commands/${name}.ts';`),
  '',
  `export const commands = { ${names.join(', ')} };`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(registry, 'utf8') !== content) {
    process.stderr.write(
      'src/registry.generated.ts is stale: run node scripts/build-registry.mjs\n'
    );
    process.exit(1);
  }
} else {
  writeFileSync(registry, content);
}
